"""OpenAI and compatible LLM API provider with structured schema validation."""

import json
from typing import Dict, Any
import httpx
from .provider import AIProvider
from app.core.config import settings

SYSTEM_PROMPT = """You are a specialized Dynamical Systems Scientific Co-Investigator in the AI Butterfly Effect Lab.
Your role is to formulate speculative what-if branching hypotheses conditioned on VERIFIED NUMERICAL SIMULATION FACTS.

CRITICAL ARCHITECTURAL DIRECTIVE:
1. The numerical simulator is the single source of truth.
2. YOU MUST NEVER PRETEND TO BE THE NUMERICAL SIMULATOR. Do NOT attempt to calculate ODE trajectories or invent numerical coordinates.
3. Clearly distinguish empirical computed facts from speculative theoretical hypotheses.
4. Always provide explicit assumptions, causal branches, epistemic uncertainties, and scientific limitations.

You must respond strictly with valid JSON conforming to the requested schema.
"""


class OpenAIProvider(AIProvider):
    name = "openai"

    def __init__(self, api_key: str = "", model: str = "gpt-4o-mini"):
        self.api_key = api_key or settings.AI_API_KEY
        self.model = model or settings.AI_MODEL

    async def generate_scenario(
        self,
        prompt: str,
        numerical_context: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Call OpenAI API with structured response schema."""
        if not self.api_key:
            raise ValueError("OpenAI API key not configured")

        user_content = (
            f"USER WHAT-IF EXPLORATION PROMPT:\n{prompt}\n\n"
            f"VERIFIED NUMERICAL SIMULATION CONTEXT (GROUND TRUTH FACT):\n"
            f"{json.dumps(numerical_context, indent=2)}\n\n"
            f"Generate a rigorous, structured speculative scenario exploring potential causal branches."
        )

        schema = {
            "type": "object",
            "properties": {
                "scenario_title": {"type": "string"},
                "assumptions": {"type": "array", "items": {"type": "string"}},
                "branches": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {
                            "id": {"type": "string"},
                            "trigger": {"type": "string"},
                            "effects": {"type": "array", "items": {"type": "string"}},
                            "time_horizon": {"type": "string", "enum": ["short", "medium", "long"]},
                            "uncertainties": {"type": "array", "items": {"type": "string"}}
                        },
                        "required": ["id", "trigger", "effects", "time_horizon", "uncertainties"],
                        "additionalProperties": False
                    }
                },
                "limitations": {"type": "array", "items": {"type": "string"}}
            },
            "required": ["scenario_title", "assumptions", "branches", "limitations"],
            "additionalProperties": False
        }

        async with httpx.AsyncClient(timeout=30.0) as client:
            response = await client.post(
                "https://api.openai.com/v1/chat/completions",
                headers={
                    "Authorization": f"Bearer {self.api_key}",
                    "Content-Type": "application/json"
                },
                json={
                    "model": self.model,
                    "messages": [
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": user_content}
                    ],
                    "response_format": {
                        "type": "json_schema",
                        "json_schema": {
                            "name": "scenario_response",
                            "strict": True,
                            "schema": schema
                        }
                    },
                    "temperature": 0.4
                }
            )

            if response.status_code != 200:
                raise RuntimeError(f"OpenAI API error ({response.status_code}): {response.text}")

            result_json = response.json()
            raw_content = result_json["choices"][0]["message"]["content"]
            parsed = json.loads(raw_content)

            parsed["provenance_status"] = "SPECULATIVE SCENARIO - AI GENERATED HYPOTHESIS"
            parsed["verified_numerical_facts"] = {
                "reference_context": numerical_context,
                "note": "These numerical facts were computed by the numerical engine, not generated by AI."
            }
            parsed["ai_provider"] = f"openai-{self.model}"
            return parsed
